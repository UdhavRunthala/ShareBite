import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import { connectDatabase, closeDatabase } from '../src/db.js';
import { seedDatabase } from '../src/seed.js';
import { createApp } from '../src/app.js';
import { User, Listing, Order, Review } from '../src/models/index.js';
import { issueToken } from '../src/auth.js';
import { mealsFor } from '../src/recognition.js';
let app;
before(async () => { app = createApp(await connectDatabase()); await seedDatabase(); });
after(closeDatabase);
test('seed creates rich histories, live windows and three working demo roles', async () => {
  assert.equal(await User.countDocuments({ role: 'donor' }), 26);
  assert.equal(await User.countDocuments({ role: 'ngo', verificationStatus: 'verified' }), 12);
  assert.equal(await Order.countDocuments({ status: 'Distributed' }), 36);
  assert.equal(await Review.countDocuments(), 72);
  assert.ok(await Listing.countDocuments({ status: 'Available', pickupBy: { $gt: new Date() } }) >= 20);
  for (const role of ['donor', 'ngo', 'admin']) {
    const response = await request(app).post('/api/auth/demo').send({ role });
    assert.equal(response.status, 200);
    assert.equal(response.body.user.role, role);
  }
  await seedDatabase();
  assert.equal(await Listing.countDocuments(), 68);
});
test('claim is atomic and exact addresses stay hidden until confirmed', async () => {
  const donor = await User.findOne({ email: 'donor@demo.com' });
  const ngos = await User.find({ role: 'ngo', verificationStatus: 'verified' }).limit(2);
  const response = await request(app).post('/api/listings').set('Authorization', `Bearer ${issueToken(donor)}`).send({ foodName: 'Test meal boxes', description: 'Freshly cooked meals packed for our community.', category: 'Cooked meals', dietType: 'veg', quantity: '20 kg', servings: 80, cookedAt: new Date(), pickupBy: new Date(Date.now() + 3600000), location: { type: 'Point', coordinates: [75.80321,26.90612] }, neighbourhood: 'C-Scheme', exactAddress: 'Private kitchen, 42 Community Lane, Jaipur', safetyDeclared: true });
  assert.equal(response.status, 201);
  const listingId = response.body._id;
  const publicView = await request(app).get(`/api/listings/${listingId}`);
  assert.equal(publicView.body.exactAddress, undefined);
  assert.deepEqual(publicView.body.location.coordinates, [75.8,26.91]);
  const claims = await Promise.all(ngos.map(ngo => request(app).post(`/api/listings/${listingId}/claim`).set('Authorization', `Bearer ${issueToken(ngo)}`)));
  assert.deepEqual(claims.map(r => r.status).sort(), [201,409]);
  const winner = ngos[claims.findIndex(r => r.status === 201)];
  const privateView = await request(app).get(`/api/listings/${listingId}`).set('Authorization', `Bearer ${issueToken(winner)}`);
  assert.equal(privateView.body.exactAddress, 'Private kitchen, 42 Community Lane, Jaipur');
  assert.equal(await Order.countDocuments({ listing: listingId }), 1);
});
test('distribution requires pickup and owned proof, increments meals once and enables reviews', async () => {
  const listing = await Listing.findOne({ foodName: 'Test meal boxes' });
  const order = await Order.findOne({ listing: listing._id });
  const ngo = await User.findById(order.ngo), donor = await User.findById(order.donor);
  const ngoAuth = `Bearer ${issueToken(ngo)}`, donorAuth = `Bearer ${issueToken(donor)}`;
  const image = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
  const uploaded = await request(app).post('/api/uploads').set('Authorization',ngoAuth).field('kind','proof').attach('file',image,'proof.png');
  assert.equal(uploaded.status,201);
  const proof = { photo: uploaded.body.url, peopleFed: 75, note: 'Shared at the community table.' };
  const premature = await request(app).post(`/api/orders/${order._id}/proof`).set('Authorization',ngoAuth).send(proof);
  assert.equal(premature.status,409);
  const pickup = await request(app).patch(`/api/orders/${order._id}/status`).set('Authorization',ngoAuth).send({ status:'Picked Up' });
  assert.equal(pickup.status,200);
  const before = await mealsFor(donor._id);
  const completed = await request(app).post(`/api/orders/${order._id}/proof`).set('Authorization',ngoAuth).send(proof);
  assert.equal(completed.status,200);
  assert.equal(await mealsFor(donor._id),before + 75);
  const duplicate = await request(app).post(`/api/orders/${order._id}/proof`).set('Authorization',ngoAuth).send(proof);
  assert.equal(duplicate.status,409);
  const review = await request(app).post(`/api/orders/${order._id}/reviews`).set('Authorization',donorAuth).send({ rating:5,text:'A thoughtful and timely collection.' });
  assert.equal(review.status,201);
  const outsider = await User.findOne({ role:'ngo',_id:{$ne:ngo._id} });
  const denied = await request(app).get(uploaded.body.url).set('Authorization',`Bearer ${issueToken(outsider)}`);
  assert.equal(denied.status,403);
});
test('chat masks contact details and rejects nonparticipants', async () => {
  const listing = await Listing.findOne({ foodName:'Test meal boxes' });
  const order = await Order.findOne({ listing:listing._id });
  const ngo = await User.findById(order.ngo);
  const sent = await request(app).post(`/api/chat/${order._id}`).set('Authorization',`Bearer ${issueToken(ngo)}`).send({ text:'Call +91 98765 43210 or hello@example.com, @team please.' });
  assert.equal(sent.status,201);
  assert.equal(sent.body.maskedText.includes('98765'),false);
  assert.equal(sent.body.text,undefined);
  const outsider = await User.findOne({ role:'ngo',_id:{$ne:ngo._id} });
  const denied = await request(app).get(`/api/chat/${order._id}`).set('Authorization',`Bearer ${issueToken(outsider)}`);
  assert.equal(denied.status,404);
});
test('admin reviews private documents and bans invalidate existing tokens', async () => {
  const admin=await User.findOne({role:'admin'}), donor=await User.findOne({email:'donor@demo.com'});
  const adminAuth=`Bearer ${issueToken(admin)}`, donorAuth=`Bearer ${issueToken(donor)}`;
  assert.equal((await request(app).get('/api/admin/users').set('Authorization',donorAuth)).status,403);
  const users=await request(app).get('/api/admin/users').set('Authorization',adminAuth);
  const pending=users.body.find(user=>user.role==='ngo'&&user.verificationStatus==='pending');
  assert.equal((await request(app).get(pending.profile.documents[0])).status,403);
  assert.equal((await request(app).get(pending.profile.documents[0]).set('Authorization',adminAuth)).headers['content-type'],'application/pdf');
  const approved=await request(app).patch(`/api/admin/users/${pending._id}`).set('Authorization',adminAuth).send({verificationStatus:'verified'});
  assert.equal(approved.status,200);
  await request(app).patch(`/api/admin/users/${donor._id}`).set('Authorization',adminAuth).send({banned:true});
  assert.equal((await request(app).get('/api/auth/me').set('Authorization',donorAuth)).status,401);
  await request(app).patch(`/api/admin/users/${donor._id}`).set('Authorization',adminAuth).send({banned:false});
});

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
const [title, nextBranch] = process.argv.slice(2);
if (!title) throw new Error('Usage: node scripts/finish-branch.mjs "PR title" [next-branch]');
const root = process.cwd().replaceAll('\\', '/');
const run = (bin, args, capture = false) => execFileSync(bin, args, { stdio: capture ? 'pipe' : 'inherit', encoding: 'utf8', shell: process.platform === 'win32' && bin === 'npm' });
const git = (...args) => run('git', ['-c', `safe.directory=${root}`, ...args], true).trim();
const branch = git('branch', '--show-current');
if (branch === 'main') throw new Error('Finish a feature branch, never main.');
const document = `docs/pull-requests/${branch.replaceAll('/', '-')}.md`;
if (!existsSync(document)) throw new Error(`Missing PR description: ${document}`);
run('npm', ['run', 'lint']);
run('npm', ['run', 'build']);
if (existsSync('server/test/platform.test.js')) run('npm', ['run', 'test']);
writeFileSync(document, readFileSync(document, 'utf8').replace('- [ ] Lint/build passes', '- [x] Lint/build passes'));
git('add', document);
if (git('diff', '--cached', '--name-only')) git('commit', '-m', `docs(workflow): record verification for ${branch}`, '-m', 'Record the reviewed branch scope and successful lint/build results. Preserve the PR description in the repository for future reference.');
git('push', '-u', 'origin', branch);
const url = run('gh', ['pr', 'create', '--base', 'main', '--head', branch, '--title', title, '--body-file', document], true).trim();
console.log(url);
run('gh', ['pr', 'merge', url, '--merge']);
git('switch', 'main');
git('pull', '--ff-only', 'origin', 'main');
git('branch', '-d', branch);
git('push', 'origin', '--delete', branch);
if (nextBranch) git('switch', '-c', nextBranch);
